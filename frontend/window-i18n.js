const uppercaseKeys = new Map(Object.keys(translations).map(key => [key.toUpperCase(), key]));
export function windowText(text, lang) {
  if ((lang !== 'en' && lang !== 'pt') || typeof text !== 'string') return text;
  const key = Object.hasOwn(translations, text) ? text : uppercaseKeys.get(text);
  return key ? translations[key][lang === 'en' ? 0 : 1] : text;
}

// Las selecciones publicadas tienen un texto base. Solo se traducen patrones
// conocidos. El nombre de un equipo o jugador y la línea quedan intactos.
export function windowSelection(text, lang) {
  if (lang !== 'en' && lang !== 'pt') return text;
  const value = String(text ?? '');
  const english = lang === 'en';
  const patterns = [
    [/^Gana (.+)$/, english ? '$1 to win' : '$1 vence'],
    [/^(.+) o empate$/, english ? '$1 or draw' : '$1 ou empate'],
    [/^(.+) o (.+) \(sin empate\)$/, english ? '$1 or $2 (no draw)' : '$1 ou $2 (sem empate)'],
    [/^(.+) gana \(empate devuelve\)$/, english ? '$1 to win (draw no bet)' : '$1 vence (empate anula)'],
    [/^(.+) gana sin recibir gol$/, english ? '$1 to win to nil' : '$1 vence sem sofrer gols'],
  ];
  for (const [pattern, label] of patterns) {
    if (pattern.test(value)) return value.replace(pattern, label);
  }
  const total = /^(Más|Menos) de (\d+(?:[.,]\d+)?)(?: (goles|córners|tarjetas|puntos|juegos|sets))?$/i.exec(value);
  if (total) {
    const [, side, line, unit] = total;
    const label = english ? side.toLowerCase() === 'más' ? 'Over' : 'Under' : side.toLowerCase() === 'más' ? 'Mais de' : 'Menos de';
    const number = english ? line.replace(',', '.') : line.replace('.', ',');
    return `${label} ${number}${unit ? ' ' + windowText(unit.charAt(0).toUpperCase() + unit.slice(1), lang).toLowerCase() : ''}`;
  }
  return windowText(value, lang);
}

